-- Extensión necesaria para la restricción de solapamiento de contratos
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ------------------------------------------------------------
--  Limpieza (permite volver a ejecutar el script)
-- ------------------------------------------------------------
DROP TABLE IF EXISTS finalizacion_contrato CASCADE;
DROP TABLE IF EXISTS pago CASCADE;
DROP TABLE IF EXISTS contrato CASCADE;
DROP TABLE IF EXISTS inquilino CASCADE;
DROP TABLE IF EXISTS departamento CASCADE;
DROP TABLE IF EXISTS usuario CASCADE;
DROP TABLE IF EXISTS tipo_personeria CASCADE;

DROP VIEW IF EXISTS vw_contrato_detalle CASCADE;
DROP VIEW IF EXISTS vw_pago_detalle CASCADE;

-- ------------------------------------------------------------
--  TABLAS
-- ------------------------------------------------------------
CREATE TABLE tipo_personeria (
    idtipopersoneria INTEGER PRIMARY KEY,
    nombre           VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE usuario (
    idusuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario   VARCHAR(30)  NOT NULL UNIQUE,
    clave     VARCHAR(100) NOT NULL,
    nombre    VARCHAR(80)  NOT NULL,
    rol       VARCHAR(20)  NOT NULL DEFAULT 'ADMIN',
    estado    VARCHAR(15)  NOT NULL DEFAULT 'Activo',
    CONSTRAINT ck_usuario_estado CHECK (estado IN ('Activo', 'Inactivo'))
);


CREATE TABLE departamento (
    iddepartamento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero         VARCHAR(10)  NOT NULL UNIQUE,
    piso           INTEGER      NOT NULL,
    direccion      VARCHAR(150) NOT NULL,
    precio_mensual NUMERIC(10,2) NOT NULL,
    estado         VARCHAR(20)  NOT NULL DEFAULT 'Disponible',
    CONSTRAINT ck_departamento_piso    CHECK (piso >= 0),
    CONSTRAINT ck_departamento_precio  CHECK (precio_mensual > 0),
    CONSTRAINT ck_departamento_estado  CHECK (estado IN ('Disponible', 'Ocupado', 'Mantenimiento'))
);

CREATE TABLE inquilino (
    idinquilino      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni              VARCHAR(8)  NOT NULL UNIQUE,
    nombre           VARCHAR(80) NOT NULL,
    apellido         VARCHAR(80) NOT NULL,
    telefono         VARCHAR(15),
    direccion        VARCHAR(150),
    idtipopersoneria INTEGER,
    rep_legal        VARCHAR(60),
    ruc              VARCHAR(11),
    direccion_fiscal VARCHAR(60),
    CONSTRAINT fk_inquilino_tipo FOREIGN KEY (idtipopersoneria)
        REFERENCES tipo_personeria (idtipopersoneria),
    CONSTRAINT ck_inquilino_dni CHECK (dni ~ '^[0-9]{8}$'),
    CONSTRAINT ck_inquilino_ruc CHECK (ruc IS NULL OR ruc ~ '^[0-9]{10,11}$')
);

CREATE TABLE contrato (
    idcontrato       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_inicio     DATE NOT NULL,
    fecha_fin        DATE NOT NULL,
    monto_mensual    NUMERIC(10,2) NOT NULL,
    estado           VARCHAR(20) NOT NULL DEFAULT 'Vigente',
    idinquilino      BIGINT NOT NULL,
    iddepartamento   BIGINT NOT NULL,
    fecha_contrato   TIMESTAMP NOT NULL,
    cantidad_persona INTEGER NOT NULL DEFAULT 1,
    CONSTRAINT fk_contrato_inquilino FOREIGN KEY (idinquilino)
        REFERENCES inquilino (idinquilino),
    CONSTRAINT fk_contrato_departamento FOREIGN KEY (iddepartamento)
        REFERENCES departamento (iddepartamento),
    CONSTRAINT ck_contrato_fechas   CHECK (fecha_fin > fecha_inicio),
    CONSTRAINT ck_contrato_monto    CHECK (monto_mensual > 0),
    CONSTRAINT ck_contrato_personas CHECK (cantidad_persona > 0),
    CONSTRAINT ck_contrato_estado   CHECK (estado IN ('Vigente', 'Finalizado', 'Anulado')),

    -- Regla del informe: un departamento no puede tener dos contratos
    -- vigentes con rangos de fechas superpuestos.
    CONSTRAINT ex_contrato_solapamiento
        EXCLUDE USING gist (
            iddepartamento WITH =,
            daterange(fecha_inicio, fecha_fin, '[]') WITH &&
        ) WHERE (estado = 'Vigente')
);

CREATE TABLE pago (
    idpago     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_pago DATE NOT NULL,
    periodo    DATE NOT NULL,
    monto      NUMERIC(10,2) NOT NULL,
    metodo     VARCHAR(30) NOT NULL,
    idcontrato BIGINT NOT NULL,
    descuento  NUMERIC(10,2) NOT NULL DEFAULT 0,
    igv        NUMERIC(10,2) NOT NULL DEFAULT 0,
    CONSTRAINT fk_pago_contrato FOREIGN KEY (idcontrato)
        REFERENCES contrato (idcontrato),
    CONSTRAINT ck_pago_monto     CHECK (monto > 0),
    CONSTRAINT ck_pago_descuento CHECK (descuento >= 0),
    CONSTRAINT ck_pago_igv       CHECK (igv >= 0),
    CONSTRAINT ck_pago_metodo    CHECK (metodo IN ('Efectivo', 'Transferencia', 'Yape', 'Plin', 'Tarjeta'))
);

CREATE TABLE finalizacion_contrato (
    id_finalizacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idcontrato      BIGINT NOT NULL,
    fecha           TIMESTAMP NOT NULL,
    motivo          VARCHAR(20) NOT NULL,
    CONSTRAINT fk_finalizacion_contrato FOREIGN KEY (idcontrato)
        REFERENCES contrato (idcontrato),
    CONSTRAINT uq_finalizacion_contrato UNIQUE (idcontrato),
    CONSTRAINT ck_finalizacion_motivo CHECK (motivo IN ('Fin de plazo', 'Rescisión', 'Incumplimiento', 'Mutuo acuerdo'))
);

-- ------------------------------------------------------------
--  ÍNDICES
-- ------------------------------------------------------------
CREATE INDEX idx_contrato_departamento ON contrato (iddepartamento);
CREATE INDEX idx_contrato_inquilino    ON contrato (idinquilino);
CREATE INDEX idx_contrato_estado       ON contrato (estado);
CREATE INDEX idx_pago_contrato         ON pago (idcontrato);
CREATE INDEX idx_pago_periodo          ON pago (periodo);
CREATE INDEX idx_inquilino_apellido    ON inquilino (apellido, nombre);

-- ------------------------------------------------------------
--  VISTAS DE CONSULTA
-- ------------------------------------------------------------
CREATE VIEW vw_contrato_detalle AS
SELECT c.idcontrato,
       c.fecha_inicio,
       c.fecha_fin,
       c.monto_mensual,
       c.estado,
       c.cantidad_persona,
       d.iddepartamento,
       d.numero          AS departamento,
       d.direccion,
       i.idinquilino,
       i.dni,
       i.nombre || ' ' || i.apellido AS inquilino,
       i.telefono
FROM contrato c
JOIN departamento d ON d.iddepartamento = c.iddepartamento
JOIN inquilino i    ON i.idinquilino = c.idinquilino;

CREATE VIEW vw_pago_detalle AS
SELECT p.idpago,
       p.fecha_pago,
       p.periodo,
       p.monto,
       p.descuento,
       p.igv,
       p.metodo,
       c.idcontrato,
       d.numero AS departamento,
       i.nombre || ' ' || i.apellido AS inquilino
FROM pago p
JOIN contrato c     ON c.idcontrato = p.idcontrato
JOIN departamento d ON d.iddepartamento = c.iddepartamento
JOIN inquilino i    ON i.idinquilino = c.idinquilino;

