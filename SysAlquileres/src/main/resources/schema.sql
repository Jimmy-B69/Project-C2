-- ============================================================
--  ESQUEMA DEL SISTEMA DE GESTIÓN DE ALQUILERES
--  Compatible con H2 (modo PostgreSQL) y PostgreSQL
-- ============================================================

CREATE TABLE IF NOT EXISTS tipo_personeria (
    idtipopersoneria INTEGER PRIMARY KEY,
    nombre           VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS usuario (
    idusuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario   VARCHAR(30)  NOT NULL UNIQUE,
    clave     VARCHAR(100) NOT NULL,
    nombre    VARCHAR(80)  NOT NULL,
    rol       VARCHAR(20)  NOT NULL DEFAULT 'ADMIN',
    estado    VARCHAR(15)  NOT NULL DEFAULT 'Activo'
);

CREATE TABLE IF NOT EXISTS departamento (
    iddepartamento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero         VARCHAR(10) NOT NULL UNIQUE,
    piso           INTEGER NOT NULL,
    direccion      VARCHAR(150) NOT NULL,
    precio_mensual NUMERIC(10,2) NOT NULL,
    estado         VARCHAR(20) NOT NULL DEFAULT 'Disponible'
);

CREATE TABLE IF NOT EXISTS inquilino (
    idinquilino      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni              VARCHAR(8) NOT NULL UNIQUE,
    nombre           VARCHAR(80) NOT NULL,
    apellido         VARCHAR(80) NOT NULL,
    telefono         VARCHAR(15),
    direccion        VARCHAR(150),
    idtipopersoneria INTEGER,
    rep_legal        VARCHAR(60),
    ruc              VARCHAR(11),
    direccion_fiscal VARCHAR(60),
    CONSTRAINT fk_inquilino_tipo FOREIGN KEY (idtipopersoneria)
        REFERENCES tipo_personeria (idtipopersoneria)
);

CREATE TABLE IF NOT EXISTS contrato (
    idcontrato       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_inicio     DATE NOT NULL,
    fecha_fin        DATE NOT NULL,
    monto_mensual    NUMERIC(10,2) NOT NULL,
    estado           VARCHAR(20) NOT NULL DEFAULT 'Vigente',
    idinquilino      BIGINT NOT NULL,
    iddepartamento   BIGINT NOT NULL,
    fecha_contrato   TIMESTAMP NOT NULL,
    cantidad_persona INTEGER NOT NULL DEFAULT 1,
    CONSTRAINT fk_contrato_inquilino FOREIGN KEY (idinquilino)
        REFERENCES inquilino (idinquilino),
    CONSTRAINT fk_contrato_departamento FOREIGN KEY (iddepartamento)
        REFERENCES departamento (iddepartamento)
);

CREATE TABLE IF NOT EXISTS pago (
    idpago      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_pago  DATE NOT NULL,
    periodo     DATE NOT NULL,
    monto       NUMERIC(10,2) NOT NULL,
    metodo      VARCHAR(30) NOT NULL,
    idcontrato  BIGINT NOT NULL,
    descuento   NUMERIC(10,2) NOT NULL DEFAULT 0,
    igv         NUMERIC(10,2) NOT NULL DEFAULT 0,
    CONSTRAINT fk_pago_contrato FOREIGN KEY (idcontrato)
        REFERENCES contrato (idcontrato)
);

CREATE TABLE IF NOT EXISTS finalizacion_contrato (
    id_finalizacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idcontrato      BIGINT NOT NULL,
    fecha           TIMESTAMP NOT NULL,
    motivo          VARCHAR(20) NOT NULL,
    CONSTRAINT fk_finalizacion_contrato FOREIGN KEY (idcontrato)
        REFERENCES contrato (idcontrato)
);

CREATE INDEX IF NOT EXISTS idx_contrato_departamento ON contrato (iddepartamento);
CREATE INDEX IF NOT EXISTS idx_contrato_inquilino ON contrato (idinquilino);
CREATE INDEX IF NOT EXISTS idx_pago_contrato ON pago (idcontrato);
